"""
columnar_transposition.py - Columnar Transposition Cipher Implementation
Design and Development of a Classical Cryptography Toolkit
Course: Network Security | Class: Final Year (ECM) 2026-27

Principle:
    Columnar Transposition is a transposition cipher where plaintext is written
    horizontally into a grid of width W (the length of the key). The ciphertext is
    then generated by reading the grid vertically column-by-column, ordered according
    to the alphabetical or numeric rank of each key character.

Irregular Grid Handling:
    - If message length N is not a multiple of width W, the last row is incomplete.
    - Columns with index c < (N % W) contain ceil(N / W) characters.
    - Columns with index c >= (N % W) contain floor(N / W) characters.
    - Our decryption algorithm precisely tracks column lengths, ensuring 100% exact
      round-trip recovery for arbitrary message lengths without requiring padding.
"""

import math
from typing import List
from src.validators import validate_text, validate_columnar_key


def columnar_encrypt(plaintext: str, key: str) -> str:
    """
    Encrypt plaintext using Columnar Transposition Cipher.
    
    Args:
        plaintext: The input text.
        key: Keyword (e.g. 'ZEBRA') or space-separated numbers.
        
    Returns:
        Ciphertext string.
    """
    validate_text(plaintext, allow_empty=True)
    col_order = validate_columnar_key(key)
    
    n = len(plaintext)
    w = len(col_order)
    
    if n <= 1 or w <= 1:
        return plaintext
        
    # Group text into columns
    # Column c gets characters at indices c, c + w, c + 2w, ...
    columns = [[] for _ in range(w)]
    for idx, char in enumerate(plaintext):
        col = idx % w
        columns[col].append(char)
        
    # Read columns in specified permutation order
    result = []
    for col_idx in col_order:
        result.extend(columns[col_idx])
        
    return "".join(result)


def columnar_decrypt(ciphertext: str, key: str) -> str:
    """
    Decrypt ciphertext using Columnar Transposition Cipher.
    
    Args:
        ciphertext: The input ciphertext.
        key: Keyword or numeric key used during encryption.
        
    Returns:
        Decrypted plaintext.
    """
    validate_text(ciphertext, allow_empty=True)
    col_order = validate_columnar_key(key)
    
    n = len(ciphertext)
    w = len(col_order)
    
    if n <= 1 or w <= 1:
        return ciphertext
        
    num_full_cols = n % w
    rows_base = n // w
    
    # Calculate length of each physical column (0 to w-1)
    col_lengths = [
        rows_base + (1 if (num_full_cols != 0 and c < num_full_cols) else 0)
        for c in range(w)
    ]
    
    # Slices from ciphertext according to reading order
    columns = [[] for _ in range(w)]
    char_ptr = 0
    for col_idx in col_order:
        length = col_lengths[col_idx]
        columns[col_idx] = list(ciphertext[char_ptr:char_ptr + length])
        char_ptr += length
        
    # Read off row-by-row
    result = []
    max_rows = math.ceil(n / w)
    for r in range(max_rows):
        for c in range(w):
            if r < len(columns[c]):
                result.append(columns[c][r])
                
    return "".join(result)
